"""Markdown export of a reviewed run (FR-11): requirement -> findings -> tests."""
from __future__ import annotations

AGENT_NAMES = {"functional": "Functional", "non_functional": "Non-functional",
               "security": "Security", "consistency": "Consistency"}


def build_report(run: dict) -> str:
    out = [f"# ReqGuard review report (run {run['id']})", "",
           f"- Created: {run['created_at']}",
           f"- Source: {'idea, drafted by the Idea-to-SRS agent' if run['source_type'] == 'idea' else 'uploaded SRS'}",
           f"- Quality score: **{run['score']}/100** ({run['grade']})",
           f"- Model: {_models(run)}",
           (f"- Requirements: {len(run['requirements'])} · Findings: {len(run['findings'])} · "
            f"Tests: {sum(1 for t in run['tests'] if t['status'] in ('accept', 'edit'))} approved"),
           (f"- Rule findings: {sum(1 for f in run['findings'] if f['source'] == 'rule')} (scored) · "
            f"AI advisory: {sum(1 for f in run['findings'] if f['source'] == 'ai')} (not scored)"), "",
           "## Summary", "", run["summary"] or "", ""]

    doc_level = [f for f in run["findings"] if f["req_id"] is None]
    if doc_level:
        out += ["## Whole-document findings", ""]
        out += [_finding_line(f) for f in doc_level] + [""]

    out += ["## Requirements", ""]
    for q in run["requirements"]:
        out.append(f"### {q['id']} ({q['kind'].replace('_', '-')}, line {q['line']})")
        out.append("")
        out.append(f"> {q['text']}")
        if q["final_text"] != q["text"]:
            out += ["", f"**Revised:** {q['final_text']}"]
        own = [f for f in run["findings"] if f["req_id"] == q["id"]]
        if own:
            out += ["", "Findings:"] + [_finding_line(f) for f in own]
        tests = [t for t in run["tests"] if t["req_id"] == q["id"] and t["status"] in ("accept", "edit")]
        if tests:
            out += ["", "Acceptance tests:"]
            out += [f"- **{t['id']}** Given {t['given']}, when {t['when']}, then {t['then']}." for t in tests]
        out.append("")

    if run["dropped"]:
        out += ["## Dropped by the grounding check", ""]
        out += [f"- \"{d['text']}\" ({d['reason']})" for d in run["dropped"]] + [""]
    out += ["---", ("Generated by ReqGuard. Rule findings are deterministic; AI findings are advisory; "
                    "every item above was decided by a human reviewer.")]
    return "\n".join(out) + "\n"


def _models(run: dict) -> str:
    """Model(s) recorded in the run usage; runs saved before the field existed say 'not recorded'."""
    models = sorted({u.get("model") for u in run.get("usage") or [] if u.get("model")})
    return ", ".join(models) if models else "not recorded"


def _finding_line(f: dict) -> str:
    source = f"Rule {f['rule_id']}" if f["source"] == "rule" else "AI advisory"
    decision = {"accept": "accepted", "edit": "edited", "reject": "rejected", "open": "open"}[f["status"]]
    line = (f"- **{f['id']}** [{f['severity']}] {AGENT_NAMES.get(f['agent'], f['agent'])} · {source}: "
            f"{f['problem']} *Decision: {decision}*")
    if f["reason"]:
        line += f" ({f['reason']})"
    return line
